def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_None_\n"
    sep = " | ".join("---" for _ in headers)
    head = " | ".join(headers)
    lines = [f"| {head} |", f"| {sep} |"]
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(lines) + "\n"


def _html_table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "<p><em>None</em></p>"
    th = "".join(f"<th>{h}</th>" for h in headers)
    body_rows = ""
    for row in rows:
        tds = "".join(f"<td>{c}</td>" for c in row)
        body_rows += f"<tr>{tds}</tr>"
    return f"<table><thead><tr>{th}</tr></thead><tbody>{body_rows}</tbody></table>"


def render_markdown(data: dict) -> str:
    pr_rows = [
        [f"[#{p['number']}]({p['url']})", p["title"][:60], p["author"], p["created"][:10]]
        for p in data["open_prs"]
    ]
    issue_rows = [
        [f"[#{i['number']}]({i['url']})", i["title"][:60], i["author"], i["created"][:10]]
        for i in data["open_issues"]
    ]
    commit_rows = [
        [f"[`{c['sha']}`]({c['url']})", c["message"][:60], c["author"], c["date"][:10]]
        for c in data["recent_commits"]
    ]
    wf_rows = [
        [w["workflow"], w["status"], w["conclusion"] or "-", f"[#{w['run_number']}]({w['url']})", w["created"][:10]]
        for w in data["workflow_runs"]
    ]

    return MARKDOWN_TEMPLATE.format(
        generated_at=data["generated_at"],
        source_repo=data["source_repo"],
        pr_count=len(pr_rows),
        pr_table=_md_table(["PR", "Title", "Author", "Created"], pr_rows),
        issue_count=len(issue_rows),
        issue_table=_md_table(["Issue", "Title", "Author", "Created"], issue_rows),
        commit_table=_md_table(["SHA", "Message", "Author", "Date"], commit_rows),
        workflow_table=_md_table(["Workflow", "Status", "Conclusion", "Run", "Date"], wf_rows),
    )


def render_html(data: dict) -> str:
    def link(url: str, label: str) -> str:
        return f'<a href="{url}">{label}</a>'

    pr_rows = [
        [link(p["url"], f"#{p['number']}"), p["title"][:60], p["author"], p["created"][:10]]
        for p in data["open_prs"]
    ]
    issue_rows = [
        [link(i["url"], f"#{i['number']}"), i["title"][:60], i["author"], i["created"][:10]]
        for i in data["open_issues"]
    ]
    commit_rows = [
        [link(c["url"], c["sha"]), c["message"][:60], c["author"], c["date"][:10]]
        for c in data["recent_commits"]
    ]
    wf_rows = [
        [w["workflow"], w["status"], w["conclusion"] or "-",
         link(w["url"], f"#{w['run_number']}"), w["created"][:10]]
        for w in data["workflow_runs"]
    ]

    return HTML_TEMPLATE.format(
        generated_at=data["generated_at"],
        source_repo=data["source_repo"],
        pr_count=len(pr_rows),
        pr_html=_html_table(["PR", "Title", "Author", "Created"], pr_rows),
        issue_count=len(issue_rows),
        issue_html=_html_table(["Issue", "Title", "Author", "Created"], issue_rows),
        commit_html=_html_table(["SHA", "Message", "Author", "Date"], commit_rows),
        workflow_html=_html_table(["Workflow", "Status", "Conclusion", "Run", "Date"], wf_rows),
    )


# ---------------------------------------------------------------------------
# Push to REPORTS repo
# ---------------------------------------------------------------------------
def push_report(gh: Github, md_content: str, html_content: str, json_data: dict) -> None:
    repo = gh.get_repo(REPORTS_REPO)
    timestamp = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d")

    files = {
        "cyberworld/latest.md":               md_content,
        f"cyberworld/archive/{timestamp}.md": md_content,
        "cyberworld/latest.html":             html_content,
        "cyberworld/latest.json":             json.dumps(json_data, indent=2),
    }

    for path, content in files.items():
        commit_msg = f"chore(report): update CyberWorld report {timestamp}"
        encoded = content.encode("utf-8")
        try:
            existing = repo.get_contents(path, ref=REPORT_BRANCH)
            repo.update_file(path, commit_msg, encoded, existing.sha, branch=REPORT_BRANCH)
            print(f"  ✔ Updated {path}")
        except GithubException:
            repo.create_file(path, commit_msg, encoded, branch=REPORT_BRANCH)
            print(f"  ✔ Created {path}")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main() -> None:
    print("🌐 CyberWorld Report Generator")
    print(f"  Source  : {SOURCE_REPO}")
    print(f"  Reports : {REPORTS_REPO}")
    print()

    gh = _gh_client()

    print("📊 Collecting repository stats…")
    data = collect_repo_stats(gh)

    print("📝 Rendering reports…")
    md_report   = render_markdown(data)
    html_report = render_html(data)

    print("🚀 Pushing reports to Personfu/REPORTS…")
    push_report(gh, md_report, html_report, data)

    print("\n✅ Done!")


if __name__ == "__main__":
    main()
