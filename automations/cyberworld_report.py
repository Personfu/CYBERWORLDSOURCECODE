#!/usr/bin/env python3
"""
cyberworld_report.py
====================
Generates HTML and Markdown reports for CyberWorld / FLLC activity
and pushes them to the Personfu/REPORTS repository.

Triggered by: .github/workflows/cyberworld-reports.yml
"""

from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests
from github import Github, GithubException


# ---------------------------------------------------------------------------
# Configuration (injected via GitHub Actions secrets / env vars)
# ---------------------------------------------------------------------------
GITHUB_TOKEN   = os.environ.get("GH_PAT") or os.environ.get("GITHUB_TOKEN", "")
SOURCE_REPO    = os.environ.get("SOURCE_REPO",  "Personfu/CYBERWORLDSOURCECODE")
REPORTS_REPO   = os.environ.get("REPORTS_REPO", "Personfu/REPORTS")
REPORT_BRANCH  = os.environ.get("REPORT_BRANCH", "main")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def now_utc() -> str:
    return datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _gh_client() -> Github:
    if not GITHUB_TOKEN:
        raise RuntimeError("GH_PAT / GITHUB_TOKEN environment variable is not set.")
    return Github(GITHUB_TOKEN)


# ---------------------------------------------------------------------------
# Data collection
# ---------------------------------------------------------------------------
def collect_repo_stats(gh: Github) -> dict:
    """Collect open PRs, issues, latest commits, and workflow runs."""
    repo = gh.get_repo(SOURCE_REPO)

    open_prs = [
        {
            "number": pr.number,
            "title":  pr.title,
            "state":  pr.state,
            "url":    pr.html_url,
            "author": pr.user.login,
            "created": str(pr.created_at),
        }
        for pr in repo.get_pulls(state="open")
    ]

    open_issues = [
        {
            "number": iss.number,
            "title":  iss.title,
            "url":    iss.html_url,
            "author": iss.user.login,
            "created": str(iss.created_at),
        }
        for iss in repo.get_issues(state="open")
        if iss.pull_request is None
    ]

    recent_commits = [
        {
            "sha":     c.sha[:7],
            "message": c.commit.message.split("\n")[0],
            "author":  c.commit.author.name,
            "date":    str(c.commit.author.date),
            "url":     c.html_url,
        }
        for c in repo.get_commits()[:10]
    ]

    workflow_runs: list[dict] = []
    try:
        for wf in repo.get_workflows():
            for run in wf.get_runs()[:3]:
                workflow_runs.append({
                    "workflow": wf.name,
                    "status":   run.status,
                    "conclusion": run.conclusion,
                    "run_number": run.run_number,
                    "url":      run.html_url,
                    "created":  str(run.created_at),
                })
    except GithubException:
        pass  # Workflow data may not be available in all contexts

    return {
        "generated_at": now_utc(),
        "source_repo":  SOURCE_REPO,
        "open_prs":     open_prs,
        "open_issues":  open_issues,
        "recent_commits": recent_commits,
        "workflow_runs":  workflow_runs,
    }


# ---------------------------------------------------------------------------
# Report rendering
# ---------------------------------------------------------------------------
